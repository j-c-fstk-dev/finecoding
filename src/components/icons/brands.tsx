import * as React from 'react';
import type { LucideProps } from 'lucide-react';

/**
 * lucide-react 1.x removed brand icons. These keep the same outline style and
 * props (size, className, strokeWidth...) as the Lucide icons they replace.
 */
function createBrandIcon(displayName: string, children: React.ReactNode) {
  const Icon = React.forwardRef<SVGSVGElement, LucideProps>(
    ({ size = 24, color = 'currentColor', strokeWidth = 2, className, ...props }, ref) => (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke={color}
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        aria-hidden="true"
        {...props}
      >
        {children}
      </svg>
    )
  );
  Icon.displayName = displayName;
  return Icon;
}

